"""training_gym/evaluation/backends/transformers_peft.py — V69 M62 S3C.

THIS MODULE HAS NEVER BEEN RUN AGAINST A MODEL
----------------------------------------------
Its structure is reviewed and its safety-critical arguments are asserted by tests, but no
weights have been loaded, no adapter has been attached and no token has been generated by
this code. "It evaluates" is a claim only a live run can support, and this milestone does
not make it. Everything below is written so that the first live run fails loudly rather
than quietly measuring the wrong thing.

WHY EVERY FRAMEWORK IMPORT IS INSIDE A FUNCTION
-----------------------------------------------
Importing this module must cost nothing and prove nothing. ``torch``, ``transformers``
and ``peft`` are imported in exactly one place — :func:`_runtime` — which is called from
:meth:`TransformersPeftEvaluationBackend.generate` only after every preflight gate has
passed. A missing framework is a named refusal, never an install.

FAIRNESS IS THE WHOLE POINT
---------------------------
The baseline and the candidate must differ in exactly one respect: whether the adapter is
attached. So:

  * both arms load the SAME ``base_model_id`` at the SAME ``revision`` with the SAME
    tokenizer, taken from one verified reference object rather than from two config reads;
  * the generation kwargs are derived from one frozen ``GenerationPolicy``;
  * the adapter path is derived from a verified ``AdapterEvaluationReference`` and
    re-checked against ``adapter_config.json`` before any load is attempted;
  * the default strategy is ISOLATED LOADS. Reusing one loaded base model across both
    arms is faster and requires proving that attaching and detaching an adapter leaves
    no residue. This repository has never tested that, so the fast path is not the
    default and the strategy actually used is recorded in every result.

RESOURCE CLEANUP
----------------
:meth:`release` never assumes it worked. It reports ``RELEASED`` only when the handles it
dropped were the handles it held; anything else is ``FAILED`` or ``UNKNOWN``, and the
runner treats a non-safe cleanup status as grounds to quarantine rather than to continue —
because the failure mode is one candidate's adapter still being attached when the next
evaluation calls itself a baseline.
"""
from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path

from ...training.artifacts import (
    ADAPTER_CONFIG_FILE,
    ADAPTER_WEIGHTS_FILE,
    validate_adapter_directory,
)
from ..backend import (
    BackendErrorCategory,
    BackendStatus,
    CleanupStatus,
    EvaluationRequest,
    EvaluationResult,
    FinishReason,
    blocked_result,
)
from ..generation import GenerationMode

BACKEND_ID = "transformers_peft"
BACKEND_VERSION = "m62.transformers_peft_evaluation.1"

#: The packages a live evaluation needs. ``peft`` is required even for the baseline arm
#: so that a run cannot begin, measure the baseline, and only then discover it cannot
#: load the adapter — a half-measured comparison is worse than a refused one.
RUNTIME_PACKAGES: tuple[str, ...] = ("torch", "transformers", "peft")

#: Never sourced from configuration. A model that executes Python from its own weights
#: directory means the measurement and the code being measured are the same untrusted
#: thing, and no configuration file, flag or backend option may grant that.
TRUST_REMOTE_CODE = False

#: Never widened. S3C does not download; a missing model is a refusal, not a fetch.
LOCAL_FILES_ONLY = True


class LoadStrategy:
    """How the two arms obtain their model. Recorded in every result.

    ``ISOLATED`` loads the base model twice — once per arm — so no state can carry from
    one to the other. ``SHARED_BASE`` would load once and toggle the adapter; it is
    named here so a future stage that can PROVE non-contamination has somewhere to put
    the proof, and it is not selectable today.
    """

    ISOLATED = "isolated_loads"
    SHARED_BASE = "shared_base_verified"


class RuntimeUnavailable(RuntimeError):
    """A framework this backend needs is not importable. Never an install trigger."""


@dataclass(frozen=True)
class _Runtime:
    """Resolved framework handles. Held only for the duration of one arm."""

    torch: object
    transformers: object
    peft: object
    versions: dict


def _runtime() -> _Runtime:
    """THE ONLY PLACE THIS SUBSYSTEM IMPORTS A MACHINE-LEARNING FRAMEWORK.

    Every failure is collected rather than raised on the first one, so an operator is
    told everything that is missing instead of discovering it one package at a time.
    """
    modules: dict[str, object] = {}
    missing: list[str] = []
    for name in RUNTIME_PACKAGES:
        try:
            modules[name] = __import__(name)
        except Exception as exc:  # noqa: BLE001 — absence must be named, not guessed
            missing.append(f"{name} ({type(exc).__name__})")
    if missing:
        raise RuntimeUnavailable(
            f"evaluation: {', '.join(missing)} could not be imported. Install the "
            f"training profile in a dedicated environment and re-run; nothing here "
            f"installs anything.")
    versions = {name: str(getattr(module, "__version__", "unknown"))
                for name, module in modules.items()}
    return _Runtime(torch=modules["torch"], transformers=modules["transformers"],
                    peft=modules["peft"], versions=versions)


def generation_kwargs(policy) -> dict:
    """Translate the frozen policy into ``generate()`` arguments. Pure, and testable.

    Kept as a module-level function precisely so a test can assert the mapping without
    importing ``transformers``: the fairness of the comparison rests on both arms
    receiving this exact dict, and that is checkable without a model.
    """
    kwargs = {
        "do_sample": bool(policy.do_sample),
        "max_new_tokens": int(policy.max_new_tokens),
        "repetition_penalty": float(policy.repetition_penalty),
    }
    if policy.mode is GenerationMode.GREEDY_DETERMINISTIC:
        # Passing temperature/top_p alongside do_sample=False makes transformers warn
        # about unused settings, and a warning nobody reads is how a sampling parameter
        # silently survives into a run that is documented as greedy.
        kwargs["num_beams"] = 1
    else:
        kwargs["temperature"] = float(policy.temperature)
        kwargs["top_p"] = float(policy.top_p)
        if policy.top_k:
            kwargs["top_k"] = int(policy.top_k)
    return kwargs


class TransformersPeftEvaluationBackend:
    """Base-model and base-plus-adapter inference. Structure reviewed, never executed."""

    backend_id = BACKEND_ID

    def __init__(self, *, load_strategy: str = LoadStrategy.ISOLATED) -> None:
        if load_strategy != LoadStrategy.ISOLATED:
            raise ValueError(
                f"evaluation backend: {load_strategy!r} is not selectable. Reusing one "
                f"loaded base model across both arms requires proving that attaching "
                f"and removing an adapter leaves no residue, and this repository has "
                f"not tested that")
        self.load_strategy = load_strategy
        self._model = None
        self._tokenizer = None
        self._runtime: _Runtime | None = None

    # -- protocol ---------------------------------------------------------------
    def version(self) -> str:
        return BACKEND_VERSION

    def readiness(self, request: EvaluationRequest) -> tuple[str, ...]:
        """Every gate that can be checked WITHOUT importing a framework.

        Runs before :func:`_runtime` is ever called, so a misconfigured request is
        refused on a host with no ``torch`` installed at all.
        """
        problems: list[str] = []
        baseline = request.baseline
        if baseline.trust_remote_code:
            problems.append("trust_remote_code is enabled; this backend never sets it")
        if baseline.revision_kind.value != "immutable_commit":
            problems.append(
                f"base model revision {baseline.base_model_revision!r} is not an "
                f"immutable commit; two runs against it would not be the same model")
        if baseline.tokenizer_identity_hash != baseline.tokenizer_identity_hash.lower():
            problems.append("tokenizer identity hash is not canonically encoded")
        if request.is_candidate:
            problems.extend(self._adapter_problems(request))
        if request.model_cache_root is None:
            problems.append(
                "no reviewed model cache root was supplied; this backend never guesses "
                "a default cache location and never downloads")
        return tuple(problems)

    def _adapter_problems(self, request: EvaluationRequest) -> list[str]:
        """Adapter checks that read JSON and bytes, and load no framework."""
        problems: list[str] = []
        adapter = request.adapter
        directory = request.adapter_directory
        if adapter is None:
            return ["the candidate arm requires a verified adapter reference"]
        if directory is None:
            return ["the candidate arm requires the directory holding verified artefacts"]
        path = Path(directory)
        if not path.is_dir():
            return [f"the adapter directory for run {adapter.run_id!r} is not a directory"]
        if path.is_symlink():
            return ["the adapter directory is a symlink; the artefacts that were "
                    "verified and the artefacts that are loaded must be the same files"]
        # Re-validate immediately before loading rather than trusting the reference: the
        # reference was built at plan time, and files can change between then and now.
        validation = validate_adapter_directory(
            path, lora=dict(adapter.lora),
            base_model_id=request.baseline.base_model_id, expect_manifest=True)
        if not validation.ok:
            problems.extend(f"adapter artefact: {p}" for p in validation.problems[:5])
        elif validation.tree_hash != adapter.adapter_artifact_tree_hash:
            problems.append(
                "the adapter artefacts no longer hash to the tree the reference was "
                "built from; something changed between planning and execution")
        if not (path / ADAPTER_CONFIG_FILE).is_file():
            problems.append(f"adapter artefact: {ADAPTER_CONFIG_FILE} is missing")
        if not (path / ADAPTER_WEIGHTS_FILE).is_file():
            problems.append(f"adapter artefact: {ADAPTER_WEIGHTS_FILE} is missing")
        if adapter.base_model_identity_hash != request.baseline.base_model_identity_hash:
            problems.append(
                "the adapter was trained against a different base model identity than "
                "the baseline arm is loading")
        if adapter.tokenizer_identity_hash != request.baseline.tokenizer_identity_hash:
            problems.append(
                "the adapter was trained against a different tokenizer identity")
        return problems

    def generate(self, request: EvaluationRequest) -> EvaluationResult:
        """Preflight, then import, then load, then generate, then release. In that order."""
        request.cancellation.raise_if_requested()
        unready = self.readiness(request)
        if unready:
            return blocked_result(request, backend_id=BACKEND_ID,
                                  backend_version=BACKEND_VERSION, reasons=unready,
                                  category=BackendErrorCategory.CONFIGURATION)
        started = time.monotonic()
        try:
            runtime = _runtime()
        except RuntimeUnavailable as exc:
            return self._failed(request, BackendErrorCategory.DEPENDENCY, str(exc),
                                started)
        self._runtime = runtime
        try:
            return self._generate(request, runtime, started)
        except MemoryError:  # pragma: no cover - requires a real model
            return self._failed(request, BackendErrorCategory.OUT_OF_MEMORY,
                                "the host ran out of memory", started)
        except OSError as exc:  # pragma: no cover - requires a real model
            # local_files_only=True reports a missing model as an OS-level error. Calling
            # that "the disk is full" would send an operator to the wrong problem.
            category = (BackendErrorCategory.MODEL_NOT_CACHED
                        if _looks_like_missing_weights(exc)
                        else BackendErrorCategory.DISK_FULL)
            return self._failed(request, category, type(exc).__name__, started)
        except Exception as exc:  # noqa: BLE001 - pragma: no cover - requires a model
            return self._failed(request, BackendErrorCategory.BACKEND,
                                type(exc).__name__, started)
        finally:
            self.release()

    # -- the part that would touch a model --------------------------------------
    def _generate(self, request: EvaluationRequest, runtime: _Runtime,
                  started: float) -> EvaluationResult:  # pragma: no cover - needs a model
        """Load, generate, and return. Never executed in this milestone."""
        baseline = request.baseline
        policy = request.generation
        transformers, torch = runtime.transformers, runtime.torch

        transformers.set_seed(policy.seed)
        tokenizer = transformers.AutoTokenizer.from_pretrained(
            baseline.tokenizer_id, revision=baseline.tokenizer_revision,
            trust_remote_code=TRUST_REMOTE_CODE, local_files_only=LOCAL_FILES_ONLY)
        template = getattr(tokenizer, "chat_template", None)
        if not template:
            return self._failed(request, BackendErrorCategory.CHAT_TEMPLATE,
                                "the tokenizer carries no chat template and this build "
                                "has no reviewed one for it; refusing rather than "
                                "inventing one", started)
        if tokenizer.pad_token is None:
            tokenizer.pad_token = tokenizer.eos_token
        # Generation reads left to right, so an over-long prompt must lose its OLDEST
        # context rather than its question. Batched generation additionally requires
        # left padding, and this backend generates one prompt at a time.
        tokenizer.padding_side = "left"
        tokenizer.truncation_side = "left"
        self._tokenizer = tokenizer

        model = transformers.AutoModelForCausalLM.from_pretrained(
            baseline.base_model_id, revision=baseline.base_model_revision,
            trust_remote_code=TRUST_REMOTE_CODE, local_files_only=LOCAL_FILES_ONLY)
        model.eval()
        adapter_active = False
        if request.is_candidate:
            model = runtime.peft.PeftModel.from_pretrained(
                model, str(request.adapter_directory), is_trainable=False,
                local_files_only=LOCAL_FILES_ONLY)
            model.eval()
            # An adapter that loaded but is not ACTIVE would produce baseline output
            # under a candidate label — the single most dangerous silent failure here.
            adapter_active = bool(getattr(model, "active_adapters", None)
                                  or getattr(model, "active_adapter", None))
            if not adapter_active:
                return self._failed(request, BackendErrorCategory.ADAPTER,
                                    "the adapter loaded but reports no active adapter; "
                                    "measuring this would attribute baseline output to "
                                    "the candidate", started)
        self._model = model

        messages = []
        if request.task.system_prompt:
            messages.append({"role": "system", "content": request.task.system_prompt})
        messages.append({"role": "user", "content": request.task.user_prompt})
        # return_dict is pinned rather than left to the library. transformers 5 flipped
        # its default to True, which returns a BatchEncoding: it has no ``.shape``, so
        # the input-token count below raises AttributeError, and passing it positionally
        # to ``generate`` hands a mapping to a parameter typed as a tensor. Both fail
        # loudly here, but the value that decides it is the library's, not ours, and it
        # has already changed once.
        encoded = tokenizer.apply_chat_template(
            messages, tokenize=True, add_generation_prompt=True,
            return_tensors="pt", truncation=True, return_dict=False,
            max_length=policy.max_input_tokens)
        input_tokens = int(encoded.shape[-1])
        truncated = input_tokens >= policy.max_input_tokens
        if truncated and not policy.truncation_permitted:
            return self._failed(request, BackendErrorCategory.TRUNCATION,
                                f"the prompt needs more than {policy.max_input_tokens} "
                                f"input tokens and the policy refuses truncation; "
                                f"silently dropping evidence the task requires the "
                                f"model to cite would invalidate the task", started)
        encoded = encoded.to(model.device)

        with torch.no_grad():
            output = model.generate(encoded, **generation_kwargs(policy),
                                    pad_token_id=tokenizer.pad_token_id)
        produced = output[0][input_tokens:]
        text = tokenizer.decode(produced, skip_special_tokens=True)
        for stop in policy.stop_sequences:
            index = text.find(stop)
            if index >= 0:
                text = text[:index]
        output_tokens = int(produced.shape[-1])
        finish = (FinishReason.MAX_NEW_TOKENS if output_tokens >= policy.max_new_tokens
                  else FinishReason.END_OF_SEQUENCE)
        cleanup = self.release()
        return EvaluationResult(
            backend_id=BACKEND_ID, backend_version=BACKEND_VERSION, role=request.role,
            task_id=request.task.task_id, task_hash=request.task.task_hash,
            status=BackendStatus.SUCCEEDED, response_text=text,
            input_tokens=input_tokens, output_tokens=output_tokens,
            input_truncated=truncated,
            truncated_tokens=1 if truncated else 0,
            latency_ms=int((time.monotonic() - started) * 1000),
            peak_memory_category="unmeasured", finish_reason=finish,
            cleanup_status=cleanup,
            warnings=(f"load_strategy={self.load_strategy}",
                      f"adapter_active={adapter_active}"),
            request_parity_hash=request.parity_hash())

    # -- cleanup ----------------------------------------------------------------
    def release(self) -> CleanupStatus:
        """Drop the handles and ask the framework to reclaim. Never assume it worked.

        Reports ``UNKNOWN`` rather than ``RELEASED`` when the cache-clearing call itself
        raised, because a cleanup nobody could verify is exactly the state in which a
        candidate's adapter is still attached to what the next run calls a baseline.
        """
        had_model = self._model is not None
        self._model = None
        self._tokenizer = None
        runtime, self._runtime = self._runtime, None
        if not had_model:
            return CleanupStatus.NOT_REQUIRED
        if runtime is None:  # pragma: no cover - defensive
            return CleanupStatus.UNKNOWN
        try:
            import gc
            gc.collect()
            cuda = getattr(runtime.torch, "cuda", None)
            if cuda is not None and cuda.is_available():
                cuda.empty_cache()
        except Exception:  # noqa: BLE001 - pragma: no cover - requires a real runtime
            return CleanupStatus.UNKNOWN
        return CleanupStatus.RELEASED

    def _failed(self, request: EvaluationRequest, category: BackendErrorCategory,
                message: str, started: float) -> EvaluationResult:
        return EvaluationResult(
            backend_id=BACKEND_ID, backend_version=BACKEND_VERSION, role=request.role,
            task_id=request.task.task_id, task_hash=request.task.task_hash,
            status=BackendStatus.FAILED, error_category=category,
            error_message=str(message)[:2_000], finish_reason=FinishReason.ERROR,
            latency_ms=int((time.monotonic() - started) * 1000),
            cleanup_status=CleanupStatus.UNKNOWN,
            request_parity_hash=request.parity_hash())


def _looks_like_missing_weights(exc: BaseException) -> bool:
    """Distinguish "the weights are not cached" from "the disk is full".

    Deliberately a text probe with a narrow vocabulary: the exception types the hub
    libraries raise are not part of any stable contract, and guessing wrong in the safe
    direction (reporting a disk error) is better than claiming a model is absent when
    the volume is simply full.
    """
    text = f"{type(exc).__name__} {exc}".lower()
    markers = ("local_files_only", "not found in the local cache", "cannot find the "
               "requested files", "no such file or directory", "entrynotfound",
               "localentrynotfound", "does not appear to have a file named")
    return any(marker in text for marker in markers)


